#!/usr/bin/env python3
"""Independent stdlib-only fixture producer. Never imports production code."""
import argparse
import json
from pathlib import Path
import struct
import zlib


def cobs(data):
    # Operate on zero-separated runs rather than the codec's byte/code-index loop.
    blocks = []
    for run in data.split(b"\0"):
        while len(run) >= 254:
            blocks.append(b"\xff" + run[:254])
            run = run[254:]
        blocks.append(bytes([len(run) + 1]) + run)
    return b"".join(blocks)


def frame(kind, payload, session, sequence, request):
    raw = struct.pack("<BBBBHHQII", 0, 1, kind, 0, len(payload), 0,
                      session, sequence, request) + payload
    raw += struct.pack("<I", zlib.crc32(raw))
    return raw, cobs(raw) + b"\0"


def fixtures():
    # Values intentionally differ from author fixtures; asymmetric endian bytes.
    commands = [
        ("hello", 1, bytes.fromhex("ef cd ab 89 67 45 23 01")),
        ("get_caps", 2, b""),
        ("config", 3, bytes.fromhex("01 00 00 01 01 00 fe 0f 00 04 00 00 60 ea 00 00")),
        ("arm", 4, bytes.fromhex("ef cd ab 89")),
        ("stop_zero", 5, bytes(4)),
        ("get_status", 6, b""),
        ("release", 7, bytes.fromhex("01 23 45 67 89 ab cd ef 10 32 54 76")),
    ]
    cases = list(commands)
    for n in (0, 1, 225, 226, 227, 253, 254, 255, 479, 480, 481, 511, 512):
        for name, data in (("zeros", bytes(n)), ("ones", b"\xff" * n),
                           ("ramp", bytes(i % 256 for i in range(n)))):
            cases.append((f"{name}_{n}", 145, data))
    result = []
    for name, kind, payload in cases:
        hello = kind == 1
        session = 0 if hello else 0xF1E2D3C4B5A69788
        sequence = 1 if hello else 0x89ABCDEF
        request = 1 if hello else 0x76543210
        raw, wire = frame(kind, payload, session, sequence, request)
        result.append(dict(name=name, type=kind, session=session, sequence=sequence,
                           request=request, payload_hex=payload.hex(),
                           raw_hex=raw.hex(), frame_hex=wire.hex()))
    return result


def array(data):
    return "{" + ",".join(f"0x{b:02x}" for b in data) + "}"


def outputs():
    if zlib.crc32(b"123456789") != 0xCBF43926:
        raise RuntimeError("CRC reference check failed")
    anchors = ((b"", b"\x01"), (b"\0", b"\x01\x01"),
               (b"\0\0", b"\x01\x01\x01"),
               (b"\x11\x22\0\x33", b"\x03\x11\x22\x02\x33"),
               (bytes(range(1, 255)), b"\xff" + bytes(range(1, 255)) + b"\x01"))
    for raw, encoded in anchors:
        if cobs(raw) != encoded:
            raise RuntimeError("COBS reference check failed")
    cases = fixtures()
    header = ["/* Generated by generate_vectors.py using struct/zlib, not mt_wire. */",
              "#ifndef CONFORMANCE_VECTORS_H", "#define CONFORMANCE_VECTORS_H",
              "typedef struct { const char *name; uint8_t type; uint64_t session;",
              "uint32_t sequence, request; size_t payload_n, raw_n, frame_n;",
              "uint8_t payload[512], raw[540], frame[544]; } golden_vector;",
              "static const golden_vector golden[] = {"]
    for v in cases:
        payload, raw, wire = (bytes.fromhex(v[k]) for k in ("payload_hex", "raw_hex", "frame_hex"))
        header.append('{"%s",%du,UINT64_C(0x%016x),UINT32_C(0x%08x),UINT32_C(0x%08x),%du,%du,%du,%s,%s,%s},' % (
            v["name"], v["type"], v["session"], v["sequence"], v["request"],
            len(payload), len(raw), len(wire), array(payload or b"\0"), array(raw), array(wire)))
    header += ["};", "/* CRC of prefix length n of bytes (i * 73 + 19) % 256. */",
               "static const uint32_t prefix_crc[] = {"]
    data = bytes((i * 73 + 19) % 256 for i in range(541))
    header += [f"UINT32_C(0x{zlib.crc32(data[:n]):08x})," for n in range(541)]
    header += ["};", "#endif", ""]
    metadata = dict(schema=1, producer="Python stdlib struct + zlib and zero-run COBS",
                    wire_contract_commit="124b3f32e1e7f7282bce283baa4c9406d4d72950",
                    cases=cases)
    return {"vectors.h": "\n".join(header),
            "vectors.json": json.dumps(metadata, indent=2) + "\n"}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    here = Path(__file__).resolve().parent
    for name, data in outputs().items():
        path = here / name
        if args.check:
            if not path.is_file() or path.read_text() != data:
                raise SystemExit(f"fixture differs: {path}")
        else:
            path.write_text(data)
    print("Reference fixtures verified" if args.check else "Reference fixtures generated")


if __name__ == "__main__":
    main()
